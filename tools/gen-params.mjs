// Writes src/engine/dspparams.js from the parameter tables in the DSP (dsp/midm/drum_voice.cc and
// master_clipper.cc), read
// out of the built web/wasm/midm.wasm, so the page's controls always match the C++.
//   node tools/gen-params.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { readSpec } from '../src/engine/plaits.js';

const mod = new WebAssembly.Module(readFileSync(new URL('../web/wasm/midm.wasm', import.meta.url)));
const { params, models, clip } = readSpec(mod);
const src = `// mi/dm — generated by tools/gen-params.mjs from dsp/midm/drum_voice.cc. Do not edit.
// [id, min, max, default, curve, label, model (-1 shared)], in the DSP's parameter order
export const DSP_SPEC = [
${params.map((p) => '  ' + JSON.stringify(p) + ',').join('\n')}
];
export const MODEL_NAMES = ${JSON.stringify(models)};
// master clipper (dsp/midm/master_clipper.cc): [id, min, max, default, curve, label]
export const CLIP_SPEC = [
${clip.map((p) => '  ' + JSON.stringify(p) + ',').join('\n')}
];
`;
writeFileSync(new URL('../src/engine/dspparams.js', import.meta.url), src);
console.log(`src/engine/dspparams.js: ${params.length} parameters, ${models.length} models`);
